//! `read_image` tool — reads an image via a separate vision model.
//!
//! Registered only when the main conversation model does not support image
//! inputs (`supports_images = false`) and `default_vision_model` is configured.
//! The tool sends the image to the vision model with an optional instruction
//! and returns the model's text description to the LLM.

use std::path::Path;

use async_openai::types::chat::ImageUrl;
use async_trait::async_trait;
use robit_ai::{
    ChatCompletionRequestMessage, ChatCompletionRequestMessageContentPartImage,
    ChatCompletionRequestMessageContentPartText, ChatCompletionRequestUserMessage,
    ChatCompletionRequestUserMessageContent, ChatCompletionRequestUserMessageContentPart, LlmClient,
};
use serde::Deserialize;
use serde_json::Value;

use super::{resolve_path, Tool, ToolContext, ToolResult};
use crate::error::Result;
use crate::media;

/// Default instruction sent to the vision model when the LLM does not provide
/// one. Chinese matches the project's prompt language.
const DEFAULT_PROMPT: &str = "详细描述这张图片的内容。如果图片中包含文字，请完整提取。";

/// Supported image formats (same set as the `read` tool).
const IMAGE_EXTENSIONS: [&str; 5] = ["png", "jpg", "jpeg", "gif", "webp"];

/// Size limit: 20MB, same as the `read` tool. OpenAI-compatible APIs
/// typically allow up to ~20MB base64-encoded images.
const MAX_IMAGE_BYTES: u64 = 20 * 1024 * 1024;

pub struct ReadImageTool {
    /// Client bound to the configured vision model.
    client: LlmClient,
    /// Max dimension (longest side, px) for images sent to the vision model;
    /// larger images are downscaled and re-encoded as JPEG (0 disables).
    max_image_dimension: u32,
    /// Max output bytes before truncation of the description.
    max_output_bytes: usize,
}

#[derive(Debug, Deserialize)]
struct ReadImageArgs {
    file_path: String,
    #[serde(default)]
    prompt: Option<String>,
}

impl ReadImageTool {
    pub fn new(client: LlmClient, max_image_dimension: u32, max_output_bytes: usize) -> Self {
        Self {
            client,
            max_image_dimension,
            max_output_bytes,
        }
    }

    /// Read the image and describe it with the vision model.
    async fn describe_image(&self, path: &Path, prompt: &str) -> ToolResult {
        // Size limit check before encoding.
        let size = match tokio::fs::metadata(path).await {
            Ok(m) => m.len(),
            Err(e) => return ToolResult::error(format!("Failed to read image metadata: {}", e)),
        };
        if size > MAX_IMAGE_BYTES {
            return ToolResult::error(format!(
                "Image too large: {} bytes (max {} bytes)",
                size, MAX_IMAGE_BYTES
            ));
        }

        let encoded = match media::encode_file_base64(path, self.max_image_dimension).await {
            Ok(e) => e,
            Err(e) => return ToolResult::error(format!("Failed to read image: {}", e)),
        };

        let messages = build_vision_messages(prompt, &encoded.data_url);
        match self.client.chat(messages, None).await {
            Ok(response) => {
                let description = response
                    .choices
                    .first()
                    .and_then(|c| c.message.content.as_ref())
                    .map(|c| c.trim())
                    .unwrap_or_default();
                if description.is_empty() {
                    return ToolResult::error("Vision model returned an empty response");
                }
                ToolResult::success(truncate_output(description, self.max_output_bytes))
            }
            Err(e) => ToolResult::error(format!("Vision model call failed: {}", e)),
        }
    }
}

#[async_trait]
impl Tool for ReadImageTool {
    fn name(&self) -> &str {
        "read_image"
    }

    fn description(&self) -> &str {
        "Read an image file (PNG, JPEG, GIF, WebP) and return its content as a text \
         description, generated by a separate vision model. Use this when you need to \
         understand an image's content, extract text shown in an image (OCR), or analyze \
         a screenshot. For text files, use the read tool."
    }

    fn parameters_schema(&self) -> Value {
        serde_json::json!({
            "type": "object",
            "properties": {
                "file_path": {
                    "type": "string",
                    "description": "Image file path (relative or absolute). Supported formats: PNG, JPEG, GIF, WebP"
                },
                "prompt": {
                    "type": "string",
                    "description": "Optional instruction for the vision model, e.g. \"Extract all text in the image\". Default: describe the image in detail"
                }
            },
            "required": ["file_path"]
        })
    }

    fn requires_confirmation(&self) -> bool {
        false
    }

    async fn execute(&self, args: Value, ctx: &ToolContext) -> Result<ToolResult> {
        let parsed: ReadImageArgs = match serde_json::from_value(args) {
            Ok(a) => a,
            Err(e) => return Ok(ToolResult::error(format!("Argument parsing failed: {}", e))),
        };

        // Resolve file path
        let path = resolve_path(&parsed.file_path, &ctx.working_dir);

        if !path.exists() {
            return Ok(ToolResult::error(format!("File not found: {}", path.display())));
        }
        if path.is_dir() {
            return Ok(ToolResult::error(format!(
                "'{}' is a directory, not a file",
                path.display()
            )));
        }

        // Only image files are accepted; text files belong to the read tool.
        let extension = path
            .extension()
            .and_then(|e| e.to_str())
            .map(|e| e.to_ascii_lowercase())
            .unwrap_or_default();
        if !IMAGE_EXTENSIONS.contains(&extension.as_str()) {
            return Ok(ToolResult::error(format!(
                "Unsupported image format '{}'. Supported formats: PNG, JPEG, GIF, WebP. \
                 For text files, use the read tool.",
                extension
            )));
        }

        // Fall back to the default instruction when the prompt is missing/blank.
        let prompt = parsed
            .prompt
            .as_deref()
            .map(str::trim)
            .filter(|p| !p.is_empty())
            .unwrap_or(DEFAULT_PROMPT);

        Ok(self.describe_image(&path, prompt).await)
    }
}

/// Build the single multimodal user message sent to the vision model:
/// a text part carrying the instruction, followed by the image.
fn build_vision_messages(prompt: &str, data_url: &str) -> Vec<ChatCompletionRequestMessage> {
    vec![ChatCompletionRequestMessage::User(
        ChatCompletionRequestUserMessage {
            content: ChatCompletionRequestUserMessageContent::Array(vec![
                ChatCompletionRequestUserMessageContentPart::Text(
                    ChatCompletionRequestMessageContentPartText {
                        text: prompt.to_string(),
                        prompt_cache_breakpoint: None,
                    },
                ),
                ChatCompletionRequestUserMessageContentPart::ImageUrl(
                    ChatCompletionRequestMessageContentPartImage {
                        image_url: ImageUrl {
                            url: data_url.to_string(),
                            detail: None,
                        },
                        prompt_cache_breakpoint: None,
                    },
                ),
            ]),
            name: None,
        },
    )]
}

/// Truncate `text` to at most `max_bytes` UTF-8 bytes without splitting a
/// character (CJK descriptions are common), appending a marker when cut.
fn truncate_output(text: &str, max_bytes: usize) -> String {
    if text.len() <= max_bytes {
        return text.to_string();
    }
    let mut end = max_bytes;
    while end > 0 && !text.is_char_boundary(end) {
        end -= 1;
    }
    format!("{}\n[... output truncated: {} bytes max]", &text[..end], max_bytes)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn build_vision_messages_shape() {
        let messages = build_vision_messages("describe", "data:image/png;base64,abc");
        assert_eq!(messages.len(), 1);
        match &messages[0] {
            ChatCompletionRequestMessage::User(msg) => {
                match &msg.content {
                    ChatCompletionRequestUserMessageContent::Array(parts) => {
                        assert_eq!(parts.len(), 2);
                        // Text part first, carrying the instruction.
                        match &parts[0] {
                            ChatCompletionRequestUserMessageContentPart::Text(t) => {
                                assert_eq!(t.text, "describe");
                            }
                            other => panic!("expected text part, got {:?}", other),
                        }
                        // Image part second, carrying the data URL.
                        match &parts[1] {
                            ChatCompletionRequestUserMessageContentPart::ImageUrl(img) => {
                                assert_eq!(img.image_url.url, "data:image/png;base64,abc");
                                assert!(img.image_url.detail.is_none());
                            }
                            other => panic!("expected image part, got {:?}", other),
                        }
                    }
                    other => panic!("expected array content, got {:?}", other),
                }
            }
            other => panic!("expected user message, got {:?}", other),
        }
    }

    #[test]
    fn truncate_output_keeps_char_boundary() {
        // 6 CJK chars = 18 bytes; limit 10 bytes must not split a char.
        let text = "你好世界测试";
        let out = truncate_output(text, 10);
        assert!(out.starts_with("你好世"));
        assert!(out.contains("truncated"));
        // Within budget: unchanged.
        assert_eq!(truncate_output("hello", 10), "hello");
    }

    #[tokio::test]
    async fn execute_rejects_non_image_file() {
        let tool = ReadImageTool::new(
            LlmClient::from_resolved(test_vision_model()),
            1024,
            51200,
        );
        // Use a real text file (this source file) via absolute path.
        let src = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("src/tool/read_image.rs");
        let ctx = test_ctx();
        let args = serde_json::json!({ "file_path": src.to_string_lossy() });
        let result = tool.execute(args, &ctx).await.unwrap();
        assert!(result.is_error);
        assert!(result.content.contains("Unsupported image format"));
    }

    #[tokio::test]
    async fn execute_missing_file() {
        let tool = ReadImageTool::new(
            LlmClient::from_resolved(test_vision_model()),
            1024,
            51200,
        );
        let ctx = test_ctx();
        let args = serde_json::json!({ "file_path": "no/such/file.png" });
        let result = tool.execute(args, &ctx).await.unwrap();
        assert!(result.is_error);
        assert!(result.content.contains("File not found"));
    }

    /// Minimal ResolvedModel for client construction (no network happens in
    /// the error-path tests above).
    fn test_vision_model() -> robit_ai::ResolvedModel {
        robit_ai::ResolvedModel {
            profile_name: "test".to_string(),
            model_id: "test-vl".to_string(),
            base_url: "http://localhost:1".to_string(),
            api_key: "test-key".to_string(),
            max_tokens: None,
            temperature: None,
            context_window: None,
            supports_images: true,
            supports_tools: false,
        }
    }

    fn test_ctx() -> ToolContext {
        struct DummyFrontend;
        #[async_trait]
        impl crate::frontend::Frontend for DummyFrontend {
            async fn on_event(&self, _: crate::event::AgentEvent) -> Result<()> {
                Ok(())
            }
            async fn request_tool_confirmation(
                &self,
                _: &crate::tool::ToolCallInfo,
            ) -> Result<bool> {
                Ok(true)
            }
        }
        let (done_tx, _done_rx) = tokio::sync::mpsc::channel(1);
        ToolContext {
            working_dir: std::path::PathBuf::from("."),
            session_id: "sess".to_string(),
            tool_call_id: "tc".to_string(),
            frontend: std::sync::Arc::new(DummyFrontend),
            extensions: std::collections::HashMap::new(),
            supports_images: false,
            async_runner: crate::tool::async_runner::AsyncTaskRunner::new(done_tx),
            cancel_token: tokio_util::sync::CancellationToken::new(),
            task_registry: crate::tool::task_registry::TaskRegistry::new(),
        }
    }
}
